#!/usr/bin/env python3
"""
Emits MuJoCo MJCF for both AURIGA robots:

    auriga_manipulator.xml   mecanum base + 4-DOF arm + parallel gripper
    auriga_car.xml           Ackermann car + pan/tilt RGB-D mast

Dimensions match the two URDF packages one-for-one, with two deliberate
differences where MuJoCo can do better than Gazebo:

  * the mecanum rollers are real bodies with hinge joints and capsule contacts,
    so the base slides sideways because of the physics rather than because a
    plugin cheats. 12 rollers per wheel instead of the URDF's 9 - fewer
    rollers means a lumpier ride over the contact gaps.
  * roller ring radius is pinned to WH_R - ROLLER_R so the rolling radius is
    exactly the nominal wheel radius.

Both files are meant to be <include/>-ed by scene_*.xml, which adds the floor,
lights and skybox.
"""

import math
