def M(name, rgba, spec=0.25, shin=0.3):
    return (f'    <material name="{name}" rgba="{rgba}" '
            f'specular="{spec}" shininess="{shin}"/>')


def inertial(mass, i, pos="0 0 0"):
    return (f'      <inertial pos="{pos}" mass="{mass:.4f}" '
            f'diaginertia="{i[0]:.7f} {i[1]:.7f} {i[2]:.7f}"/>')


def box_i(m, x, y, z):
    return (m * (y * y + z * z) / 12, m * (x * x + z * z) / 12,
            m * (x * x + y * y) / 12)


def cyl_i(m, r, h, axis="z"):
    ir, ia = m * (3 * r * r + h * h) / 12, m * r * r / 2
    return {"x": (ia, ir, ir), "y": (ir, ia, ir), "z": (ir, ir, ia)}[axis]


def gbox(mat, size, pos="0 0 0", euler=None, cls="visual", name=None):
    e = f' euler="{euler}"' if euler else ""
    n = f' name="{name}"' if name else ""
    return (f'      <geom{n} class="{cls}" type="box" size="{size}" '
            f'pos="{pos}"{e} material="{mat}"/>')


def gcyl(mat, r, half, pos="0 0 0", euler=None, cls="visual", name=None):
    e = f' euler="{euler}"' if euler else ""
    n = f' name="{name}"' if name else ""
    return (f'      <geom{n} class="{cls}" type="cylinder" size="{r:.4f} {half:.4f}" '
            f'pos="{pos}"{e} material="{mat}"/>')


