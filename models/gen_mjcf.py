# In-model lidar rays. Each one is a site + a rangefinder sensor, so this
# stays modest; lidar.py casts arbitrarily many with mj_multiRay instead.
N_LIDAR = 24

def lidar_ring(prefix, n, indent="        "):
    """Sites for a spinning 2D lidar: n rays evenly spaced in the body xy plane.

    A rangefinder measures along its site's +z, and euler="0 1.5708 theta" swings
    that z into the horizontal plane at bearing theta (0 = body +x, CCW).
    """
    out = []
    for i in range(n):
        th = 2 * math.pi * i / n
        out.append(f'{indent}<site name="{prefix}{i:02d}" pos="0 0 0" '
                   f'euler="0 1.5708 {th:.5f}" size="0.0015" '
                   f'rgba="0.2 0.8 0.9 0.35"/>')
    return out


def lidar_sensors(prefix, n, cutoff):
    return "\n".join(
        f'    <rangefinder name="{prefix}{i:02d}" site="{prefix}{i:02d}" '
        f'cutoff="{cutoff}"/>' for i in range(n))


def plate_obj(path, lx, ly, lz, title):
    """Thin slab whose +/-Y faces carry the whole texture, other faces a corner texel.

    Written with one unique vertex per face corner (24 verts / 24 UVs). Sharing
    vertices between faces leaves fewer UVs than vertices, and the mesh then
    renders as a flat wash of one texel instead of showing the artwork.
    """
    hx, hy, hz = lx / 2, ly / 2, lz / 2
    full = [(0, 0), (1, 0), (1, 1), (0, 1)]
    edge = [(0.02, 0.02)] * 4
    faces = [
        # (corner positions in winding order, uvs, normal)
        ([(hx, -hy, -hz), (-hx, -hy, -hz), (-hx, -hy, hz), (hx, -hy, hz)], full, (0, -1, 0)),
        ([(-hx, hy, -hz), (hx, hy, -hz), (hx, hy, hz), (-hx, hy, hz)], full, (0, 1, 0)),
        ([(-hx, -hy, hz), (-hx, hy, hz), (hx, hy, hz), (hx, -hy, hz)], edge, (0, 0, 1)),
        ([(-hx, -hy, -hz), (hx, -hy, -hz), (hx, hy, -hz), (-hx, hy, -hz)], edge, (0, 0, -1)),
        ([(hx, -hy, -hz), (hx, hy, -hz), (hx, hy, hz), (hx, -hy, hz)], edge, (1, 0, 0)),
        ([(-hx, -hy, -hz), (-hx, -hy, hz), (-hx, hy, hz), (-hx, hy, -hz)], edge, (-1, 0, 0)),
    ]
    L = [f"# {title} - generated by gen_mjcf.py"]
    V, VT, VN, F = [], [], [], []
    for corners, uvs, n in faces:
        VN.append(n)
        idx = []
        for c, uv in zip(corners, uvs):
            V.append(c)
            VT.append(uv)
            idx.append(len(V))
        F.append((idx, len(VN)))
    L += ["v %.6f %.6f %.6f" % v for v in V]
    L += ["vt %.4f %.4f" % t for t in VT]
    L += ["vn %.1f %.1f %.1f" % n for n in VN]
    for idx, ni in F:
        L.append("f " + " ".join(f"{i}/{i}/{ni}" for i in idx))
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


